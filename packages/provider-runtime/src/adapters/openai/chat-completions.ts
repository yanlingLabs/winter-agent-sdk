// `openai-chat-completions@1` — the OpenAI Chat Completions API, and every surface that speaks it:
// DeepSeek, OpenRouter, Azure's deployment path, and the twelve local servers.
//
// The wire differs from Responses in every part that matters, which is why this is a second adapter
// rather than a flag on the first: messages instead of input items, `tool_calls` on the assistant
// message instead of standalone `function_call` items, arguments assembled by INDEX rather than by
// item id, usage behind `stream_options.include_usage` instead of on the completion event, and
// `reasoning_effort` as a top-level field instead of a `reasoning` object.
//
// DEEPSEEK'S EXPOSED REASONING IS THE ONE STRUCTURAL ADDITION, and §6.3 of the continuity report is
// the reason it cannot be optional: with `tools` present, ALL preceding `reasoning_content` must be
// replayed or the next request fails with a 400 — a hard error, not a degradation
// (`toolLoopRequirement: "hard-error"` in the descriptor). So the adapter captures it as
// `native_state` (whose only sink is the provider-state sidecar) AND surfaces it as
// `thinking_exposed_delta` (which is what makes a portable cross-family handoff possible at all),
// and replays it verbatim onto the assistant message inside its own continuation domain.
//
// 0.0.56 adds three OpenRouter behaviours, each gated on the row's own evidence:
//   - W1: an Anthropic model routed through OpenRouter (`openrouter`, upstream id `anthropic/*`, row
//     `promptCaching: true`) gets Anthropic's `cache_control` breakpoints -- the system prompt as cache-
//     marked text parts (from `systemBlocks`), and the rolling and lookback message markers -- with each
//     marker's lifetime from `cacheTtl`/`messageCacheTtl` (W3's rules, `adapters/cache-ttl.ts`).
//   - W5: OpenRouter's reported `usage.cost` (USD) rides the usage event as `reportedCostUsd`, and its
//     `prompt_tokens_details.cache_write_tokens` as `cacheWriteTokens`.
//   - W7: `reasoning_details` (OpenRouter's normalized reasoning blocks: text with a signature, summary,
//     encrypted) is captured whole as native state and replayed VERBATIM on the model's own next turn,
//     for a row whose continuation is `opaque-provider-state` -- a Claude tool loop through OpenRouter
//     breaks without it ("the entire sequence of consecutive reasoning blocks must match the outputs
//     generated by the model", https://openrouter.ai/docs/use-cases/reasoning-tokens).
//
// 2026-10-29 (continuation audit) adds Gemini's thought signatures on Google's OpenAI-compatible
// endpoint (`google-openai`): each `tool_calls` entry may carry `extra_content.google.thought_signature`,
// and "When using Gemini 4 and Gemini 3 models, you must pass back thought signatures during function
// calling, otherwise you will get a validation error (4xx status code)"
// (https://ai.google.dev/gemini-api/docs/generate-content/thought-signatures, "Signatures for OpenAI
// compatibility"). The entry's `extra_content` is captured whole per call id as native state and put
// back on that exact call, on the `google-openai` connection only, for a row whose continuation is
// `opaque-provider-state` -- no other chat surface defines the field.
//
// It also adds Mistral's thinking chunks. With `reasoning_effort: "high"`, Mistral's `message.content` is a
// LIST: a `ThinkChunk` (`{"type":"thinking","thinking":[TextChunk...]}`) and a `TextChunk`; streamed, the
// list arrives first, then "a single list containing both a closing ThinkChunk and the first TextChunk",
// then plain strings (https://docs.mistral.ai/studio/conversations/reasoning). A list `content` used to be
// ignored outright, which dropped the reasoning AND the answer's first words. Both chunk types are read on
// every surface now; on Mistral's own API (`mistral`, `codestral`) for a `plaintext` row the thinking is
// also captured and replayed as a ThinkChunk at the head of the assistant `content` -- "always replay the
// full assistant message (including `ThinkChunk`) back into the message history" -- instead of a
// `reasoning_content` field Mistral does not define.

