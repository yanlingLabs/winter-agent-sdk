/**
 * The chat turn, from selection validation to the last event.
 *
 * Everything refusable is refused before the endpoint is even resolved, so a rejected selection
 * leaves the fake with zero recorded requests — which is what the corpus asserts on.
 */
export async function* chatTurn(
  req: TurnRequest,
  ctx: ProviderContext,
  options: ChatTurnOptions,
  fallbackBaseUrl: string | undefined,
  urlFor: (endpoint: ResolvedEndpoint) => string,
  extraProtocolHeaders: Record<string, string> = {},
): AsyncIterable<ProviderEvent> {
  const queue = new EventQueue();
  const policy = makeRetryPolicy(options);
  let url: string;
  let headers: Record<string, string>;
  let endpoint: ResolvedEndpoint;
  let body: string;
  let captureExposed: boolean;
  let captureDetails: boolean;
  let captureExtraContent: boolean;
  let captureThinkChunks: boolean;
  try {
    const descriptor = options.descriptors?.(req.model, ctx.connection.providerId);
    assertRepresentableTools(req.tools);
    const reasoning = resolveReasoning(req, descriptor);
    const reasoningParameter = chatReasoningParameterFor(ctx.connection.providerId);
    assertWithinLimits(req, descriptor, [
      ...(reasoning.effort !== undefined ? [reasoningParameter === "reasoning-object" ? "reasoning" : "reasoning_effort"] : []),
      ...(req.maxOutputTokens !== undefined ? [descriptor?.reasoning !== undefined ? "max_completion_tokens" : "max_tokens"] : []),
      ...((req.tools?.length ?? 0) > 0 ? ["tools"] : []),
    ]);
    // `full-exposed` is the descriptor's own recorded observation of the endpoint's behaviour, not
    // an inference from the model family (§6.4 is explicit that the serving stack decides).
    // 2026-10-29 audit: AND the row's continuation is `plaintext` -- the row's own statement that the
    // endpoint takes `reasoning_content` back. A row that exposes reasoning but documents no replay
    // (Meta's Chat Completions, say) must never be sent a field its API never took.
    // 2026-10-29: Mistral's own API replays the same text as ThinkChunks inside `content` instead.
    captureThinkChunks = chatThinkChunksFor(ctx.connection.providerId, descriptor);
    captureExposed = descriptor?.reasoning?.readableState?.value === "full-exposed" && descriptor.reasoning.continuation === "plaintext" && !captureThinkChunks;
    // 0.0.56 (W7): a row whose continuation is the provider's opaque state replays `reasoning_details`.
    // 0.0.57: and only on OpenRouter -- `reasoning_details` is OpenRouter's field, and no other chat
    // surface documents taking it back; the row's evidence alone would also admit any future
    // opaque-state row on another dialect, which would then be sent a field it never defined.
    captureDetails = ctx.connection.providerId === "openrouter" && descriptor?.reasoning?.continuation === "opaque-provider-state";
    // 2026-10-29: Gemini's thought signatures, on Google's OpenAI-compatible endpoint only.
    captureExtraContent = chatToolCallExtraContentFor(ctx.connection.providerId, descriptor);
    endpoint = resolveEndpoint(ctx, options, fallbackBaseUrl);
    const auth = await resolveAuth(ctx, options.authStyle ?? "bearer");
    if (auth.material === null && !endpoint.policy.local) {
      throw capabilityRefusal(`no credential is configured for provider "${ctx.connection.providerId}" — an OpenAI-compatible endpoint that is not a declared local installation needs one`);
    }
    headers = buildHeaders({
      policy: endpoint.policy,
      protocol: { "content-type": "application/json", accept: "text/event-stream", ...extraProtocolHeaders, ...auth.headers },
      // NO `chatgpt-account-id` (fix-wave R-FW-1 / whole-branch review I-1). It is the CODEX
      // backend's header and `codex-oauth.ts` authors it there; this adapter is the one `xai-oauth`
      // composes, so the branch that used to sit here sent another vendor's product header, holding
      // an account-scoped value, to xAI's subscription proxy. `ResolvedAuth` no longer carries an
      // `accountId` at all, so there is nothing here to author it from.
      privileged: privilegedHeaders(options),
      identity: identityFor(options, ctx),
      userSupplied: ctx.connection.headers,
    });
    url = urlFor(endpoint);
    body = JSON.stringify(
      buildChatBody(req, reasoning, descriptor, captureExposed, {
        toolResultImages: chatToolResultImagesFor(ctx.connection.providerId),
        replayReasoningDetails: captureDetails,
        replayToolCallExtraContent: captureExtraContent,
        replayThinkChunks: captureThinkChunks,
        exposedReasoningField: chatExposedReasoningFieldFor(ctx.connection.providerId),
        preserveThinking: captureExposed && chatPreserveThinkingFor(ctx.connection.providerId, descriptor),
        anthropicCacheControl: openRouterAnthropicCaching(ctx.connection.providerId, descriptor),
        reasoningParameter,
      }),
    );
  } catch (err) {
    yield errorEvent(err);
    return;
  }

  let response: Response;
  try {
    response = yield* pumpEvents(
      queue,
      openStream({ url, headers, body, policy: endpoint.policy, ctx, options, ...(req.signal !== undefined ? { signal: req.signal } : {}) }, policy, (event) => queue.push(event)),
    );
  } catch (err) {
    yield errorEvent(err);
    return;
  }
  if (response.body === null) {
    yield { type: "error", error: { code: "network", message: "the provider returned no response body", retryable: false } };
    return;
  }

  const mapper = new ChatStreamMapper(captureExposed, { captureReasoningDetails: captureDetails, captureToolCallExtraContent: captureExtraContent, captureThinkChunks, reportedCost: ctx.connection.providerId === "openrouter" });
  try {
    for await (const sse of parseSse(response.body, {
      stallTimeoutMs: ctx.stallTimeoutMs,
      ...(req.signal !== undefined ? { signal: req.signal } : {}),
      onBytes: (n) => ctx.log({ kind: "provider.stream", providerId: ctx.connection.providerId, bytes: n }),
    })) {
      policy.commit();
      for (const event of mapper.map(sse.data)) yield event;
    }
    for (const event of mapper.finish()) yield event;
  } catch (err) {
    yield errorEvent(err);
  }
}

