interface PendingCall {
  id: string;
  name: string;
}

/**
 * Chat Completions SSE chunks -> Winter's normalized events.
 *
 * ARGUMENTS ARE ASSEMBLED BY `index`, NOT BY ID: only the FIRST fragment of a call carries its `id`
 * and `function.name`; every later fragment carries the index alone. An adapter keyed on id would
 * drop every continuation fragment and produce empty arguments for every call — silently.
 */
export class ChatStreamMapper {
  private started = false;
  private stopReason: "end_turn" | "tool_use" | "max_tokens" | "refusal" | undefined;
  private exposed = "";
  private completed = false;
  private readonly callsByIndex = new Map<number, PendingCall>();
  private readonly order: number[] = [];
  /**
   * 0.0.47: the live reasoning block a run of `reasoning_content` deltas is streaming into, if one is
   * open. This dialect has no reasoning block of its own: a block opens with the first reasoning delta
   * and closes when the answer (text or a tool call) begins, or when the stream completes.
   */
  private openReasoning: string | undefined;
  private reasoningBlocks = 0;

  /** 0.0.56 (W7): the turn's `reasoning_details`, joined from their streamed fragments. */
  private readonly details = new ReasoningDetailsAccumulator();
  private sawDeltaDetails = false;
  /** 2026-10-29: each call slot's `extra_content` (Gemini's thought signature), as received. */
  private readonly extraByIndex = new Map<number, Record<string, unknown>>();
  /** 2026-10-29: the turn's Mistral `ThinkChunk`s, joined from their streamed fragments. */
  private readonly thinkChunks = new ThinkChunkAccumulator();

  constructor(
    private readonly captureExposedReasoning: boolean,
    private readonly opts: { captureReasoningDetails?: boolean; captureToolCallExtraContent?: boolean; captureThinkChunks?: boolean; reportedCost?: boolean } = {},
  ) {}

  /** One piece of exposed reasoning: accumulated for the replay, streamed to the host as it arrives. */
  private pushExposed(events: ProviderEvent[], text: string): void {
    if (text.length === 0) return;
    this.exposed += text;
    events.push({ type: "thinking_exposed_delta", text });
    // 0.0.47 (user ruling 2026-10-05): raw exposed reasoning streams to the host live too -- before
    // this it reached no host at all.
    if (this.openReasoning === undefined) {
      this.openReasoning = `exposed:${this.reasoningBlocks++}`;
      events.push({ type: "reasoning_progress", block: this.openReasoning, phase: "start", kind: "exposed" });
    }
    events.push({ type: "reasoning_progress", block: this.openReasoning, phase: "delta", kind: "exposed", text });
  }

  private closeReasoning(events: ProviderEvent[]): void {
    // The answer began: the next ThinkChunk fragment, if any, is a new chunk.
    this.thinkChunks.close();
    if (this.openReasoning === undefined) return;
    events.push({ type: "reasoning_progress", block: this.openReasoning, phase: "end", kind: "exposed" });
    this.openReasoning = undefined;
  }

  map(data: string): ProviderEvent[] {
    if (isStreamTerminator(data)) return this.finalize();
    const payload = parseSseJson(data);
    if (payload === undefined) return [];
    const events: ProviderEvent[] = [];

    // A provider may report an error INSIDE a 200 stream rather than as a status.
    const inlineError = payload.error;
    if (inlineError !== null && typeof inlineError === "object") {
      const message = (inlineError as { message?: unknown }).message;
      const code = (inlineError as { code?: unknown }).code;
      // 0.0.57: OpenRouter's mid-stream error carries a NUMERIC `code` (the status it would have sent,
      // 402 for "insufficient credits") and `metadata.error_type` (`payment_required`); either, or a
      // billing code / out-of-credit sentence, makes it `billing` (https://openrouter.ai/docs/api-reference/errors).
      const billing = code === 402 || isBillingErrorBody(payload);
      return [
        {
          type: "error",
          error: { code: billing ? "billing" : "server", message: typeof message === "string" ? message : "the provider reported an error mid-stream", retryable: false, ...(typeof code === "string" ? { providerCode: code } : {}) },
        },
      ];
    }

    if (!this.started) {
      this.started = true;
      events.push({
        type: "message_start",
        ...(typeof payload.id === "string" ? { id: payload.id } : {}),
        ...(typeof payload.model === "string" ? { model: payload.model } : {}),
      });
    }

    const usage = payload.usage;
    if (usage !== null && typeof usage === "object") {
      const u = usage as { prompt_tokens?: unknown; completion_tokens?: unknown; prompt_tokens_details?: unknown; prompt_cache_hit_tokens?: unknown; completion_tokens_details?: unknown; cost?: unknown };
      const details = u.prompt_tokens_details !== null && typeof u.prompt_tokens_details === "object" ? (u.prompt_tokens_details as { cached_tokens?: unknown }).cached_tokens : undefined;
      // 0.0.56 (W5): OpenRouter's `prompt_tokens_details.cache_write_tokens` -- "tokens written to cache,
      // returned only for models with explicit caching and cache write pricing"
      // (https://openrouter.ai/docs/use-cases/usage-accounting) -- a subset of `prompt_tokens`, like the reads.
      const written = u.prompt_tokens_details !== null && typeof u.prompt_tokens_details === "object" ? (u.prompt_tokens_details as { cache_write_tokens?: unknown }).cache_write_tokens : undefined;
      // DeepSeek reports its cache hits under its own name; both are the same accounting fact.
      const cached = typeof details === "number" ? details : typeof u.prompt_cache_hit_tokens === "number" ? u.prompt_cache_hit_tokens : undefined;
      // WS-24 (I-2): `completion_tokens_details.reasoning_tokens` -- the chat-completions dialect's
      // own name for the SAME fact `responses.ts`'s `output_tokens_details.reasoning_tokens` reports
      // (DeepSeek's `deepseek-reasoner` and any other row that documents it over this wire). A SUBSET
      // of `completion_tokens`, never added on top. Absent when the row omits it.
      const reasoning =
        u.completion_tokens_details !== null && typeof u.completion_tokens_details === "object"
          ? (u.completion_tokens_details as { reasoning_tokens?: unknown }).reasoning_tokens
          : undefined;
      // Review r1 finding 5: `prompt_tokens` is the TOTAL prompt (DeepSeek's hit + miss included), and
      // the cached count a subset of it -- normalized to the seam's non-cached `inputTokens`.
      const prompt = normalizedPromptUsage(typeof u.prompt_tokens === "number" ? u.prompt_tokens : 0, cached);
      const cacheWrite = typeof written === "number" && written > 0 ? Math.min(written, prompt.inputTokens) : undefined;
      // 0.0.56 (W5): OpenRouter's own cost for the request -- "Cost in credits", and "OpenRouter uses a
      // credit system where the base currency is US dollars" (https://openrouter.ai/docs/faq). Read only on
      // the OpenRouter connection: another server's `cost` field promises no unit.
      const cost = this.opts.reportedCost === true && typeof u.cost === "number" && Number.isFinite(u.cost) && u.cost >= 0 ? u.cost : undefined;
      events.push({
        type: "usage",
        ...prompt,
        ...(cacheWrite !== undefined ? { inputTokens: prompt.inputTokens - cacheWrite, cacheWriteTokens: cacheWrite } : {}),
        outputTokens: typeof u.completion_tokens === "number" ? u.completion_tokens : 0,
        ...(typeof reasoning === "number" ? { reasoningTokens: reasoning } : {}),
        ...(cost !== undefined ? { reportedCostUsd: cost } : {}),
      });
    }

    const choices = Array.isArray(payload.choices) ? payload.choices : [];
    for (const choice of choices) {
      if (choice === null || typeof choice !== "object") continue;
      const record = choice as { delta?: unknown; finish_reason?: unknown; message?: unknown };
      events.push(...this.mapDelta(record.delta));
      // 0.0.56 (W7): a chunk that carries the COMPLETE message (the non-streaming shape,
      // `choices[].message.reasoning_details`) instead of a delta -- taken only when no delta carried any,
      // so the same entries are never counted twice.
      if (this.opts.captureReasoningDetails === true && !this.sawDeltaDetails && record.message !== null && typeof record.message === "object") {
        this.details.add((record.message as { reasoning_details?: unknown }).reasoning_details);
      }
      const finish = record.finish_reason;
      if (typeof finish === "string" && finish.length > 0) {
        for (const index of this.order) {
          const call = this.callsByIndex.get(index);
          if (call !== undefined) events.push({ type: "tool_call_end", id: call.id });
        }
        this.stopReason = finish === "tool_calls" ? "tool_use" : finish === "length" ? "max_tokens" : finish === "content_filter" ? "refusal" : "end_turn";
      }
    }
    return events;
  }

  /** The stream ended. A turn that reached a `finish_reason` is complete even without a `[DONE]` — many OpenAI-compatible servers never send one. */
  finish(): ProviderEvent[] {
    if (this.completed) return [];
    if (this.stopReason !== undefined) return this.finalize();
    return [{ type: "error", error: { code: "network", message: "the provider's stream ended before any finish_reason — the turn is incomplete", retryable: false } }];
  }

  private finalize(): ProviderEvent[] {
    if (this.completed) return [];
    this.completed = true;
    const events: ProviderEvent[] = [];
    this.closeReasoning(events);
    // Captured at COMPLETION, once, whole — the same rule the Responses surface follows, for the
    // same reason: a partial copy replayed on the next turn is a request the provider rejects.
    const items: unknown[] = [];
    if (this.captureExposedReasoning && this.exposed.length > 0) items.push({ type: "winter.exposed_reasoning", text: this.exposed } satisfies ExposedReasoningItem);
    const details = this.opts.captureReasoningDetails === true ? this.details.complete : [];
    if (details.length > 0) items.push({ type: "winter.reasoning_details", details } satisfies ReasoningDetailsItem);
    const calls: ToolCallExtraContentItem["calls"] = [];
    for (const index of this.order) {
      const call = this.callsByIndex.get(index);
      const extra = this.extraByIndex.get(index);
      if (call !== undefined && extra !== undefined) calls.push({ id: call.id, extra_content: extra });
    }
    if (calls.length > 0) items.push({ type: "winter.tool_call_extra_content", calls } satisfies ToolCallExtraContentItem);
    const chunks = this.opts.captureThinkChunks === true ? this.thinkChunks.complete : [];
    if (chunks.length > 0) items.push({ type: "winter.think_chunks", chunks } satisfies ThinkChunksItem);
    if (items.length > 0) events.push({ type: "native_state", items });
    events.push({ type: "done", stopReason: this.stopReason ?? "end_turn" });
    return events;
  }

  private mapDelta(delta: unknown): ProviderEvent[] {
    if (delta === null || typeof delta !== "object") return [];
    const record = delta as { content?: unknown; reasoning_content?: unknown; reasoning?: unknown; tool_calls?: unknown; reasoning_details?: unknown };
    const events: ProviderEvent[] = [];
    // 0.0.56 (W7): accumulated, never surfaced -- opaque continuation state (signatures, encrypted data).
    if (this.opts.captureReasoningDetails === true && record.reasoning_details !== undefined && record.reasoning_details !== null) {
      this.sawDeltaDetails = true;
      this.details.add(record.reasoning_details);
    }

    // DeepSeek spells it `reasoning_content`; OpenRouter re-exports the same channel as `reasoning`.
    // Both are FULL EXPOSED reasoning, which never becomes assistant content (R6-8).
    const exposedDelta = typeof record.reasoning_content === "string" ? record.reasoning_content : typeof record.reasoning === "string" ? record.reasoning : undefined;
    if (exposedDelta !== undefined) this.pushExposed(events, exposedDelta);

    // AFTER the reasoning, deliberately: a chunk carrying both is the reasoning's last words and the
    // answer's first, and in that order one block closes once -- handled the other way round, the answer
    // would close the block and the same chunk's reasoning open a second one after it.
    if (typeof record.content === "string" && record.content.length > 0) {
      this.closeReasoning(events);
      events.push({ type: "text_delta", text: record.content });
    } else if (Array.isArray(record.content)) {
      // 2026-10-29: a chunk LIST (Mistral's reasoning wire): ThinkChunks are exposed reasoning, TextChunks
      // the answer, in list order -- the transition list carries the closing thought AND the first words.
      for (const chunk of record.content) {
        if (chunk === null || typeof chunk !== "object" || Array.isArray(chunk)) continue;
        const c = chunk as Record<string, unknown>;
        if (c["type"] === "thinking") {
          const text = this.thinkChunks.add(c);
          this.pushExposed(events, text);
        } else if (c["type"] === "text" && typeof c["text"] === "string" && c["text"].length > 0) {
          this.closeReasoning(events);
          events.push({ type: "text_delta", text: c["text"] });
        }
      }
    }

    const toolCalls = record.tool_calls;
    if (Array.isArray(toolCalls) && toolCalls.length > 0) this.closeReasoning(events);
    if (Array.isArray(toolCalls)) {
      for (const fragment of toolCalls) {
        if (fragment === null || typeof fragment !== "object") continue;
        const f = fragment as { index?: unknown; id?: unknown; function?: unknown; extra_content?: unknown };
        const index = typeof f.index === "number" ? f.index : 0;
        const fn = f.function !== null && typeof f.function === "object" ? (f.function as { name?: unknown; arguments?: unknown }) : {};
        const existing = this.callsByIndex.get(index);
        if (existing === undefined) {
          const id = typeof f.id === "string" && f.id.length > 0 ? f.id : undefined;
          const name = typeof fn.name === "string" && fn.name.length > 0 ? fn.name : undefined;
          if (id === undefined || name === undefined) {
            // A NEW call slot with no identity is a tool invocation this adapter cannot express.
            // Assembling it under an invented id would hand the caller a call the model never named.
            events.push({
              type: "error",
              error: {
                code: "capability",
                message: `the provider opened tool call slot ${index} with no id or function name, so the call cannot be represented — Winter fails the turn rather than dropping it silently (WS-13 §9)`,
                retryable: false,
              },
            });
            continue;
          }
          this.callsByIndex.set(index, { id, name });
          this.order.push(index);
          events.push({ type: "tool_call_start", id, name });
        }
        const call = this.callsByIndex.get(index);
        // 2026-10-29: the call's `extra_content`, on whichever of its fragments carries it -- kept whole
        // and only on the connection that defines it. Never surfaced: it is opaque continuation state.
        if (call !== undefined && this.opts.captureToolCallExtraContent === true && f.extra_content !== null && typeof f.extra_content === "object" && !Array.isArray(f.extra_content)) {
          this.extraByIndex.set(index, f.extra_content as Record<string, unknown>);
        }
        if (call !== undefined && typeof fn.arguments === "string" && fn.arguments.length > 0) {
          events.push({ type: "tool_call_delta", id: call.id, argumentsJsonDelta: fn.arguments });
        }
      }
    }
    return events;
  }
}

