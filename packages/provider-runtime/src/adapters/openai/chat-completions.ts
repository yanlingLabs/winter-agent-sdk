/** Anthropic's ceiling on explicit breakpoints per request -- OpenRouter: "There is a limit of four explicit breakpoints" (https://openrouter.ai/docs/features/prompt-caching). */
const MAX_ANTHROPIC_BREAKPOINTS = 4;
/** The Anthropic adapter's own margin under the 20-block lookback window (`LOOKBACK_MARGIN_POSITIONS`). */
const CHAT_LOOKBACK_MARGIN_POSITIONS = 15;

/**
 * Whether this turn's request takes Anthropic `cache_control` breakpoints: an Anthropic model (upstream id
 * `anthropic/...`) on OpenRouter whose row documents prompt caching. Opt-in by evidence, exactly as the
 * Anthropic adapter's `promptCachingLayout`: a row silent on caching gets the plain string system prompt.
 */
export function openRouterAnthropicCaching(providerId: string, descriptor: WinterModelDescriptor | undefined): boolean {
  if (providerId !== "openrouter" || descriptor === undefined) return false;
  return descriptor.upstreamId.startsWith("anthropic/") && descriptor.promptCaching?.value === true;
}

type WirePart = Record<string, unknown>;
type WireChatMessage = { role?: unknown; content?: unknown; tool_calls?: unknown };

/** A wire message's content as parts (a plain string becomes one text part), or `undefined` when it has none to mark. */
function partsOf(message: WireChatMessage): WirePart[] | undefined {
  if (typeof message.content === "string") return message.content.length > 0 ? [{ type: "text", text: message.content }] : undefined;
  if (Array.isArray(message.content) && message.content.length > 0) return message.content as WirePart[];
  return undefined;
}

/** The index of the last text part (a breakpoint rides a text part), or -1. */
function lastTextPart(parts: readonly WirePart[]): number {
  for (let i = parts.length - 1; i >= 0; i--) if (parts[i]!["type"] === "text") return i;
  return -1;
}

/** The last message before `end` a breakpoint may carry: a user or tool message with a text part. Assistant and system messages are never marked. */
function lastMarkableChat(out: readonly WireChatMessage[], end: number): number {
  for (let m = end - 1; m >= 0; m--) {
    const role = out[m]!.role;
    if (role !== "user" && role !== "tool") continue;
    const parts = partsOf(out[m]!);
    if (parts !== undefined && lastTextPart(parts) !== -1) return m;
  }
  return -1;
}

/** Content positions strictly after message `from` up to and including message `to` -- a run of tool replies or of tool calls counts once, as in the Anthropic lookback count. */
function chatPositionsBetween(out: readonly WireChatMessage[], from: number, to: number): number {
  let count = 0;
  let previousRole: unknown;
  for (let m = from + 1; m <= to; m++) {
    const message = out[m]!;
    if (message.role === "tool") {
      if (previousRole !== "tool") count++;
    } else if (message.role === "assistant") {
      if (typeof message.content === "string" && message.content.length > 0) count++;
      if (Array.isArray(message.tool_calls) && message.tool_calls.length > 0) count++;
    } else {
      count += partsOf(message)?.length ?? 0;
    }
    previousRole = message.role;
  }
  return count;
}

function markChat(out: WireChatMessage[], m: number, ttl: CacheTtl): void {
  const parts = partsOf(out[m]!)!.slice();
  const at = lastTextPart(parts);
  parts[at] = { ...parts[at]!, cache_control: cacheControlFor(ttl) };
  out[m] = { ...out[m]!, content: parts };
}

/**
 * The message breakpoints on a chat wire, within `budget`: the ROLLING one on the last user/tool
 * message's last text part, and the LOOKBACK one on the message the previous request's rolling
 * breakpoint wrote (the last markable message before the newest assistant message) when more than
 * `CHAT_LOOKBACK_MARGIN_POSITIONS` positions were appended after it -- the Anthropic adapter's two
 * markers, mapped onto this wire's message shapes.
 */
export function withChatCacheMarkers(messages: readonly unknown[], budget: number, ttls: { rolling: CacheTtl; lookback: CacheTtl }): unknown[] {
  const out = messages.slice() as WireChatMessage[];
  if (budget <= 0) return out;
  const tail = lastMarkableChat(out, out.length);
  if (tail === -1) return out;
  markChat(out, tail, ttls.rolling);
  if (budget < 2) return out;
  let lastAssistant = -1;
  for (let m = tail; m >= 0; m--) {
    if (out[m]!.role === "assistant") {
      lastAssistant = m;
      break;
    }
  }
  if (lastAssistant <= 0) return out;
  const previousWrite = lastMarkableChat(out, lastAssistant);
  if (previousWrite !== -1 && chatPositionsBetween(out, previousWrite, tail) > CHAT_LOOKBACK_MARGIN_POSITIONS) markChat(out, previousWrite, ttls.lookback);
  return out;
}

/**
 * 0.0.56 (W7 fix): how a chat surface takes a reasoning effort.
 *
 * `"reasoning_effort"` -- OpenAI's top-level field, and every other OpenAI-compatible server's.
 * `"reasoning-object"` -- OpenRouter's documented unified parameter, `"reasoning": { "effort": "high" }`
 * ("Accepted values are max, xhigh, high, medium, low, minimal and none",
 * https://openrouter.ai/docs/use-cases/reasoning-tokens). OpenRouter's model list also names
 * `reasoning_effort`, but a Claude tool loop sent that way came back with no `reasoning_details` at all
 * (the owner's live probe, 2026-10-24), and the replay W7 depends on has nothing to replay. The row's
 * efforts ARE OpenRouter's `supported_efforts`, verbatim, so the mapped value goes through unchanged.
 */
export type ChatReasoningParameter = "reasoning_effort" | "reasoning-object";

/** The reasoning parameter a provider's chat surface takes. */
export function chatReasoningParameterFor(providerId: string): ChatReasoningParameter {
  return providerId === "openrouter" ? "reasoning-object" : "reasoning_effort";
}

/**
 * The chat request body.
 *
 * `max_completion_tokens` vs `max_tokens`: the newer spelling is required on reasoning models and
 * rejected by many local servers, and the old one is the reverse. The descriptor's own reasoning
 * evidence is what decides, which keeps the choice a recorded FACT about the model rather than a
 * guess about the endpoint. Disclosed.
 */
export function buildChatBody(
  req: TurnRequest,
  reasoning: ReasoningPlan,
  descriptor: WinterModelDescriptor | undefined,
  replayExposedReasoning: boolean,
  opts: {
    toolResultImages?: ChatToolResultImages;
    replayReasoningDetails?: boolean;
    replayToolCallExtraContent?: boolean;
    replayThinkChunks?: boolean;
    exposedReasoningField?: ChatExposedReasoningField;
    preserveThinking?: boolean;
    anthropicCacheControl?: boolean;
    reasoningParameter?: ChatReasoningParameter;
  } = {},
): Record<string, unknown> {
  const messages: unknown[] = [];
  const mapped = mapChatMessages(req.messages, replayExposedReasoning, opts);
  // 0.0.56 (W1): Anthropic's cache breakpoints through OpenRouter, only when the caller asked for the
  // cache layout (`systemBlocks`) and the row documents caching (see `openRouterAnthropicCaching`).
  if (opts.anthropicCacheControl === true && req.systemBlocks !== undefined) {
    const systemParts = req.systemBlocks.filter((block) => block.text.length > 0);
    const systemBreakpoints = systemParts.filter((block) => block.cacheScope !== null).length;
    const ttls = resolveCacheTtls(req, systemBreakpoints > 0);
    if (systemParts.length > 0) {
      messages.push({ role: "system", content: systemParts.map((block) => ({ type: "text", text: block.text, ...(block.cacheScope !== null ? { cache_control: cacheControlFor(ttls.system) } : {}) })) });
    }
    messages.push(...withChatCacheMarkers(mapped, MAX_ANTHROPIC_BREAKPOINTS - systemBreakpoints, ttls));
  } else {
    if (req.system !== undefined && req.system.length > 0) messages.push({ role: "system", content: req.system });
    messages.push(...mapped);
  }
  const tools = mapChatTools(req.tools);
  const budgetField = descriptor?.reasoning !== undefined ? "max_completion_tokens" : "max_tokens";
  return {
    model: req.model,
    messages,
    stream: true,
    // Usage does not arrive at all without this: the final chunk carrying it is opt-in.
    stream_options: { include_usage: true },
    ...(tools.length > 0 ? { tools, tool_choice: mapChatToolChoice(req.toolChoice) } : {}),
    ...(reasoning.enabled && reasoning.effort !== undefined ? (opts.reasoningParameter === "reasoning-object" ? { reasoning: { effort: reasoning.effort } } : { reasoning_effort: reasoning.effort }) : {}),
    ...(req.maxOutputTokens !== undefined ? { [budgetField]: req.maxOutputTokens } : {}),
    // 2026-10-29: the replayed reasoning is read only when asked for (see `chatPreserveThinkingFor`).
    ...(opts.preserveThinking === true && reasoning.enabled ? { preserve_thinking: true } : {}),
  };
}

