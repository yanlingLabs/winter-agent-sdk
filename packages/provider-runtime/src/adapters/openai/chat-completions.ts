/**
 * Streamed `ThinkChunk` fragments -> whole chunks. One run of thinking (until answer text or a tool call
 * begins) is ONE chunk: its inner text fragments are joined, any non-text inner chunk is kept in place,
 * and a `signature` it carries is kept. `closed` is not kept: the API documents it as "Currently only used
 * for prefixing", and a mid-stream `false` replayed would describe a chunk that never ended.
 */
class ThinkChunkAccumulator {
  private readonly chunks: Array<{ thinking: Array<Record<string, unknown>>; signature?: string }> = [];
  private open = false;

  add(chunk: Record<string, unknown>): string {
    if (!this.open) {
      this.chunks.push({ thinking: [] });
      this.open = true;
    }
    const target = this.chunks[this.chunks.length - 1]!;
    if (typeof chunk["signature"] === "string" && chunk["signature"].length > 0) target.signature = chunk["signature"];
    let text = "";
    for (const inner of Array.isArray(chunk["thinking"]) ? chunk["thinking"] : []) {
      if (inner === null || typeof inner !== "object" || Array.isArray(inner)) continue;
      const piece = inner as Record<string, unknown>;
      const last = target.thinking[target.thinking.length - 1];
      if (piece["type"] === "text" && typeof piece["text"] === "string") {
        text += piece["text"];
        if (last !== undefined && last["type"] === "text") last["text"] = `${String(last["text"])}${piece["text"]}`;
        else target.thinking.push({ type: "text", text: piece["text"] });
      } else {
        target.thinking.push({ ...piece });
      }
    }
    return text;
  }

  /** The answer (text or a call) began: the next thinking fragment opens a new chunk. */
  close(): void {
    this.open = false;
  }

  get complete(): Array<Record<string, unknown>> {
    return this.chunks.filter((c) => c.thinking.length > 0).map((c) => ({ type: "thinking", thinking: c.thinking.map((t) => ({ ...t })), ...(c.signature !== undefined ? { signature: c.signature } : {}) }));
  }
}

/** The fields of a streamed `reasoning_details` entry that arrive as FRAGMENTS of one value and are joined in order. */
const CONCATENATED_DETAIL_FIELDS = new Set(["text", "summary", "data"]);

/**
 * 0.0.56 (W7): streamed `reasoning_details` deltas -> the complete array.
 *
 * OpenRouter streams each reasoning block across chunks ("The complete reasoning sequence is built by
 * concatenating all chunks in order"); fragments of one block share its `index`. A fragment whose
 * `index` and `type` match an entry already seen is joined into it: its `text`/`summary`/`data` are
 * appended, and any other field it carries with a value (a `signature` that arrives with the last
 * fragment, an `id`, a `format`) is set. An entry with no `index`, or a new `index`/`type`, is a new
 * block. The result is the array a non-streaming response carries at `message.reasoning_details`.
 *
 * A `reasoning.encrypted` entry is never joined: it arrives whole, one blob per signed step (OpenRouter's
 * own AI SDK provider pushes each "as-is, never merged"), and Gemini sends several at one index.
 *
 * Text and summary blocks are keyed by `index` AND `type` (2026-10-29 audit): the documented types are `reasoning.text`,
 * `reasoning.summary` and `reasoning.encrypted`, and an upstream that emits two of them at one index (a
 * readable block beside its encrypted twin) interleaves their fragments. Keyed by index alone, the
 * second type took the index over and every later fragment of the first opened a new, split block --
 * a sequence the provider never produced, which "must match the outputs generated by the model".
 */
/** The `reasoning.text` formats whose text the upstream itself signs: sent back unsigned, it is refused. */
const SIGNED_TEXT_FORMATS = new Set(["anthropic-claude-v1", "google-gemini-v1"]);

/**
 * The captured `reasoning_details` as they go back, in order, otherwise verbatim. A `reasoning.text`
 * entry in a signed-text format without a `signature` is left out: Anthropic refuses it ("Invalid
 * signature in thinking block") and Google refuses Gemini's ("Corrupted thought signature") -- Gemini
 * signs its thought text internally and carries no `signature` on it at all, so its continuity rides
 * the `reasoning.encrypted` entries alone. This is the rule OpenRouter's own AI SDK provider applies on
 * replay (OpenRouterTeam/ai-sdk-provider, convert-to-openrouter-chat-messages.ts, issues #418 and #423).
 */
export function replayableReasoningDetails(details: readonly unknown[]): unknown[] {
  return details.filter((d) => {
    if (d === null || typeof d !== "object") return true;
    const entry = d as Record<string, unknown>;
    if (entry["type"] !== "reasoning.text") return true;
    // An entry naming no format is kept. OpenRouter's SDK reads a missing format as Claude's; here only
    // an entry that SAYS it is signed text is dropped, so another upstream's unlabelled text still goes back.
    if (typeof entry["format"] !== "string" || !SIGNED_TEXT_FORMATS.has(entry["format"])) return true;
    return typeof entry["signature"] === "string" && entry["signature"].length > 0;
  });
}

export class ReasoningDetailsAccumulator {
  private readonly details: Array<Record<string, unknown>> = [];
  /** `index` + `type` -> position in `details`. */
  private readonly byBlock = new Map<string, number>();

  add(fragments: unknown): void {
    // The documented form is an ARRAY; a single entry object is taken as a one-entry array rather than
    // dropped (dropping it would lose a signature the next request must carry).
    const list = Array.isArray(fragments) ? fragments : fragments !== null && typeof fragments === "object" ? [fragments] : [];
    for (const fragment of list) {
      if (fragment === null || typeof fragment !== "object" || Array.isArray(fragment)) continue;
      const piece = fragment as Record<string, unknown>;
      // An encrypted entry is a discrete, complete blob (Gemini's thought signature, an Anthropic
      // redacted block): never joined. Two of them at one index are two blobs, and their `data`
      // concatenated is a signature the upstream rejects as corrupted (0.0.61's Gemini tool loops).
      if (piece["type"] === "reasoning.encrypted") {
        this.details.push({ ...piece });
        continue;
      }
      const index = typeof piece["index"] === "number" ? piece["index"] : undefined;
      const block = index !== undefined ? `${index}\u0000${String(piece["type"])}` : undefined;
      const at = block !== undefined ? this.byBlock.get(block) : undefined;
      const target = at !== undefined ? this.details[at] : undefined;
      if (target !== undefined) {
        for (const [key, value] of Object.entries(piece)) {
          if (CONCATENATED_DETAIL_FIELDS.has(key) && typeof value === "string") target[key] = `${typeof target[key] === "string" ? (target[key] as string) : ""}${value}`;
          else if (value !== null && value !== undefined) target[key] = value;
        }
        continue;
      }
      if (block !== undefined) this.byBlock.set(block, this.details.length);
      this.details.push({ ...piece });
    }
  }

  get complete(): unknown[] {
    return this.details.map((d) => ({ ...d }));
  }
}

